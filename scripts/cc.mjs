#!/usr/bin/env node
// Client Checklist CLI for agents (zero dependencies, Node 18+).
// Edits data/clients/<id>.json, keeps ids stable, bumps rev/updatedAt, validates. You still `git commit && git push`.
//
//   node scripts/cc.mjs library                         list task library ids
//   node scripts/cc.mjs export-library                  write data/library.json (full templates, EN/ES)
//   node scripts/cc.mjs new --name "Jose Example" --lang es --case naturalization [--message "..."] [--office "..."] [--office-phone ..] [--office-email ..] [--reminder-time 18:00]
//   node scripts/cc.mjs dictate <id> "needs his birth certificate and tax transcripts by Nov 15"
//   node scripts/cc.mjs add <id> --library birth_cert [--due 2026-11-15] [--note "..."] [--to hr@x.com] [--to-name "HR"] [--phone 555-555-0100]
//   node scripts/cc.mjs add-custom <id> --title "Letter from pastor" [--text "..."] [--due ..] [--custom-json path/to/item.json]
//   node scripts/cc.mjs edit <id> <taskId> [--due ..] [--note ..] [--title ..] [--text ..] [--to ..] [--to-name ..] [--phone ..]
//   node scripts/cc.mjs remove <id> <taskId>            (tombstone: deleted=true, keeps the id)
//   node scripts/cc.mjs show <id> | link <id> | list | index
//   node scripts/cc.mjs validate [files...]             (default: all data/clients/*.json)
import fs from 'node:fs'; import path from 'node:path'; import vm from 'node:vm'; import crypto from 'node:crypto'; import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATA = path.join(ROOT, 'data/clients');
const SITE = process.env.CC_SITE || 'https://moonyose.github.io/client-checklist/';

// Load the browser library + parser into a sandbox.
const sandbox = { window: {}, console, Date, Intl, URL, TextEncoder };
sandbox.window.window = sandbox.window; sandbox.window.crypto = crypto.webcrypto;
vm.createContext(sandbox);
for (const f of ['js/library.js', 'js/common.js', 'js/parse.js']) {
  let src = fs.readFileSync(path.join(ROOT, f), 'utf8');
  vm.runInContext(`(function(window){ var LZString = window.LZString || {}; window.LZString = LZString; ${src}\n})(window);`, sandbox, { filename: f });
}
const LIB = sandbox.window.CC_LIBRARY, PARSE = sandbox.window.CC_PARSE;

const now = () => new Date().toISOString();
const rid = (p) => p + crypto.randomBytes(6).toString('hex').slice(0, 10);
const fileOf = (id) => path.join(DATA, id + '.json');
function load(id) { const p = fileOf(id); if (!fs.existsSync(p)) die(`No such client file: ${p}`); return JSON.parse(fs.readFileSync(p, 'utf8')); }
function save(doc, msg) {
  doc.rev = (doc.rev || 0) + 1; doc.updatedAt = now();
  const errs = validateDoc(doc, fileOf(doc.id)); if (errs.length) die('Refusing to save, validation failed:\n  ' + errs.join('\n  '));
  fs.mkdirSync(DATA, { recursive: true }); fs.writeFileSync(fileOf(doc.id), JSON.stringify(doc, null, 2) + '\n');
  writeIndex();
  console.log(`${msg}\nSaved ${path.relative(ROOT, fileOf(doc.id))} (rev ${doc.rev})\nClient link: ${link(doc.id)}`);
}
function writeIndex() {
  const clients = fs.readdirSync(DATA).filter(f => /^cl_[a-z0-9_]+\.json$/.test(f)).map(f => { const d = JSON.parse(fs.readFileSync(path.join(DATA, f), 'utf8')); return { id: d.id, name: d.client.name, rev: d.rev, updatedAt: d.updatedAt }; });
  fs.writeFileSync(path.join(DATA, 'index.json'), JSON.stringify({ note: 'Convenience index, regenerated by scripts/cc.mjs. The data/clients/cl_*.json files are the source of truth.', clients }, null, 2) + '\n');
}
const link = (id) => SITE + 'client.html?c=' + id;
function die(m) { console.error(m); process.exit(1); }
function args(argv) { const o = { _: [] }; for (let i = 0; i < argv.length; i++) { const a = argv[i]; if (a.startsWith('--')) { const k = a.slice(2); const v = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : true; o[k] = v; } else o._.push(a); } return o; }
const isDate = (s) => /^\d{4}-\d{2}-\d{2}$/.test(s) && !isNaN(new Date(s + 'T00:00:00'));
const isTs = (s) => typeof s === 'string' && !isNaN(Date.parse(s)) && /T/.test(s);

function newTask(library, extra = {}) {
  const t = { id: rid('tk_'), library: library || null, ...extra, createdAt: now(), updatedAt: now() };
  for (const k of Object.keys(t)) if (t[k] === undefined || t[k] === '') delete t[k];
  return t;
}
function overridesFrom(o) { const ov = {}; if (o.to) ov.to = o.to; if (o['to-name']) ov.toName = o['to-name']; if (o.phone) ov.phone = String(o.phone); return Object.keys(ov).length ? ov : undefined; }

// ---- validation (mirrors schema/client-checklist.schema.json, plus cross-checks the schema can't express) ----
function validateDoc(d, file) {
  const e = []; const req = (c, m) => { if (!c) e.push(m); };
  req(d && typeof d === 'object', 'not an object'); if (!d || typeof d !== 'object') return e;
  const allowedTop = ['$schema', 'schemaVersion', 'id', 'rev', 'createdAt', 'updatedAt', 'client', 'caseType', 'message', 'attorney', 'reminders', 'tasks'];
  Object.keys(d).forEach(k => req(allowedTop.includes(k), `unknown top-level field "${k}"`));
  req(d.schemaVersion === 1, 'schemaVersion must be 1');
  req(/^cl_[a-z0-9_]{4,40}$/.test(d.id || ''), 'id must match ^cl_[a-z0-9_]{4,40}$');
  if (file) req(path.basename(file) === d.id + '.json', `file name must be ${d.id}.json`);
  req(Number.isInteger(d.rev) && d.rev >= 1, 'rev must be an integer >= 1');
  req(isTs(d.createdAt) && isTs(d.updatedAt), 'createdAt/updatedAt must be ISO timestamps');
  req(d.client && d.client.name && ['en', 'es'].includes(d.client.language), 'client.name and client.language (en|es) required');
  req(Object.keys(LIB.CASE_TYPES).includes(d.caseType), 'caseType must be one of ' + Object.keys(LIB.CASE_TYPES).join(', '));
  if (d.reminders && d.reminders.time) req(/^([01]\d|2[0-3]):[0-5]\d$/.test(d.reminders.time), 'reminders.time must be HH:MM');
  if (d.reminders) req(!d.reminders.emailAddr && !d.reminders.phone, 'reminders.emailAddr/phone must stay empty in the public repo');
  req(Array.isArray(d.tasks), 'tasks must be an array'); if (!Array.isArray(d.tasks)) return e;
  const ids = new Set(), libs = new Set();
  d.tasks.forEach((t, i) => {
    const w = `tasks[${i}]`;
    req(/^tk_[a-z0-9_]{4,40}$/.test(t.id || ''), `${w}.id must match ^tk_[a-z0-9_]{4,40}$`);
    req(!ids.has(t.id), `${w}.id "${t.id}" is duplicated`); ids.add(t.id);
    req(t.library === null || (typeof t.library === 'string' && LIB.byId[t.library]), `${w}.library "${t.library}" is not a library id (or null)`);
    if (t.library && !t.deleted) { req(!libs.has(t.library), `${w}: library task "${t.library}" appears twice`); libs.add(t.library); }
    if (t.library === null) req(t.title || (t.custom && t.custom.title), `${w}: custom task needs title or custom.title`);
    if (t.custom) req(['doc', 'email', 'phone', 'online', 'custom'].includes(t.custom.type), `${w}.custom.type invalid`);
    if (t.custom && t.custom.phone) req(/^\+\d{8,15}$/.test(t.custom.phone), `${w}.custom.phone must be E.164 like +18005551234`);
    if (t.custom && t.custom.url) req(/^https:\/\//.test(t.custom.url), `${w}.custom.url must be https://`);
    if (t.due) req(isDate(t.due), `${w}.due must be YYYY-MM-DD`);
    req(isTs(t.createdAt) && isTs(t.updatedAt), `${w}.createdAt/updatedAt must be ISO timestamps`);
    const allowed = ['id', 'library', 'title', 'text', 'custom', 'due', 'note', 'overrides', 'createdAt', 'updatedAt', 'deleted'];
    Object.keys(t).forEach(k => req(allowed.includes(k), `${w}: unknown field "${k}"`));
  });
  return e;
}

const [cmd, ...rest] = process.argv.slice(2); const o = args(rest);
switch (cmd) {
  case 'library':
    for (const it of LIB.ITEMS) console.log(`${it.id.padEnd(24)} ${it.type.padEnd(7)} ${it.title.en}${it.phoneDisplay ? '  [' + it.phoneDisplay + (it.verified ? ' verified' : '') + ']' : ''}${it.placeholder ? '  [placeholder]' : ''}`);
    console.log('\nCase types: ' + Object.entries(LIB.CASE_TYPES).map(([k, v]) => `${k} (${v.label})`).join('; '));
    break;
  case 'export-library': {
    const out = { generatedFrom: 'js/library.js', verifiedOn: LIB.VERIFIED_ON, note: 'EXAMPLE TEMPLATES - attorney must review. Not legal advice.', fields: LIB.FIELD_DEFS, caseTypes: LIB.CASE_TYPES, items: LIB.ITEMS };
    fs.writeFileSync(path.join(ROOT, 'data/library.json'), JSON.stringify(out, null, 2) + '\n'); console.log('Wrote data/library.json'); break;
  }
  case 'new': {
    if (!o.name) die('--name required');
    const id = o.id || rid('cl_'); if (fs.existsSync(fileOf(id))) die('Exists: ' + id);
    const doc = { $schema: '../../schema/client-checklist.schema.json', schemaVersion: 1, id, rev: 0, createdAt: now(), updatedAt: now(),
      client: { name: o.name, language: o.lang === 'es' ? 'es' : 'en' }, caseType: o.case || 'other', message: o.message || '',
      attorney: { name: o.office || 'Example Immigration Law Office', phone: o['office-phone'] || '(555) 555-0100', email: o['office-email'] || 'office@example.com' },
      reminders: { email: !!o['remind-email'], sms: !!o['remind-sms'], emailAddr: '', phone: '', time: o['reminder-time'] || '09:00' }, tasks: [] };
    save(doc, `Created client ${o.name} (${id})`); break;
  }
  case 'dictate': {
    const doc = load(o._[0]); const text = o._.slice(1).join(' '); if (!text) die('text required');
    const added = [];
    for (const p of PARSE.parse(text, new Date(new Date().toDateString()))) {
      const live = doc.tasks.find(t => !t.deleted && p.libId && t.library === p.libId);
      if (live) { if (p.due && live.due !== p.due) { live.due = p.due; live.updatedAt = now(); added.push(`updated due: ${p.libId} -> ${p.due}`); } continue; }
      const t = p.libId ? newTask(p.libId, { due: p.due || undefined }) : newTask(null, { title: p.title, due: p.due || undefined });
      doc.tasks.push(t); added.push(`${t.id}  ${p.libId || 'custom: ' + p.title}${p.due ? '  due ' + p.due : ''}`);
    }
    if (!added.length) die('Nothing recognized.');
    save(doc, 'Dictation → tasks:\n  ' + added.join('\n  ')); break;
  }
  case 'add': {
    const doc = load(o._[0]); const lib = o.library; if (!LIB.byId[lib]) die(`Unknown library id "${lib}". Run: node scripts/cc.mjs library`);
    if (doc.tasks.some(t => !t.deleted && t.library === lib)) die(`Task "${lib}" is already on this list (use edit).`);
    if (o.due && !isDate(o.due)) die('--due must be YYYY-MM-DD');
    const t = newTask(lib, { due: o.due, note: o.note, overrides: overridesFrom(o) }); doc.tasks.push(t);
    save(doc, `Added ${t.id} (${lib})`); break;
  }
  case 'add-custom': {
    const doc = load(o._[0]); const custom = o['custom-json'] ? JSON.parse(fs.readFileSync(o['custom-json'], 'utf8')) : undefined;
    if (!o.title && !(custom && custom.title)) die('--title or --custom-json with title required');
    const t = newTask(null, { title: o.title || (typeof custom.title === 'string' ? custom.title : custom.title.en), text: o.text, custom, due: o.due, note: o.note, overrides: overridesFrom(o) });
    doc.tasks.push(t); save(doc, `Added custom ${t.id}`); break;
  }
  case 'edit': {
    const doc = load(o._[0]); const t = doc.tasks.find(x => x.id === o._[1] && !x.deleted); if (!t) die('No such live task: ' + o._[1]);
    for (const k of ['due', 'note', 'title', 'text']) if (o[k] !== undefined) { if (o[k] === '' || o[k] === true) delete t[k]; else t[k] = o[k]; }
    const ov = overridesFrom(o); if (ov) t.overrides = { ...(t.overrides || {}), ...ov };
    t.updatedAt = now(); save(doc, `Edited ${t.id}`); break;
  }
  case 'remove': {
    const doc = load(o._[0]); const t = doc.tasks.find(x => x.id === o._[1]); if (!t) die('No such task: ' + o._[1]);
    t.deleted = true; t.updatedAt = now(); save(doc, `Removed ${t.id} (tombstoned)`); break;
  }
  case 'show': { const d = load(o._[0]); console.log(`${d.client.name} (${d.id}) rev ${d.rev} ${d.caseType} ${d.client.language}`); d.tasks.forEach(t => console.log(`  ${t.deleted ? '✗' : '•'} ${t.id}  ${t.library || 'custom: ' + t.title}${t.due ? '  due ' + t.due : ''}`)); console.log('Link: ' + link(d.id)); break; }
  case 'link': console.log(link(o._[0])); break;
  case 'index': writeIndex(); console.log('Wrote data/clients/index.json'); break;
  case 'list': for (const f of fs.readdirSync(DATA).filter(f => /^cl_[a-z0-9_]+\.json$/.test(f))) { const d = JSON.parse(fs.readFileSync(path.join(DATA, f), 'utf8')); console.log(`${d.id}  ${d.client.name}  rev ${d.rev}  ${d.tasks.filter(t => !t.deleted).length} tasks  ${link(d.id)}`); } break;
  case 'validate': {
    const files = o._.length ? o._ : fs.readdirSync(DATA).filter(f => /^cl_[a-z0-9_]+\.json$/.test(f)).map(f => path.join(DATA, f));
    let bad = 0;
    for (const f of files) { let d; try { d = JSON.parse(fs.readFileSync(f, 'utf8')); } catch (err) { console.log(`✗ ${f}: invalid JSON (${err.message})`); bad++; continue; }
      const errs = validateDoc(d, f); if (errs.length) { bad++; console.log(`✗ ${path.relative(ROOT, path.resolve(f))}\n  ` + errs.join('\n  ')); } else console.log(`✓ ${path.relative(ROOT, path.resolve(f))}`); }
    process.exit(bad ? 1 : 0);
  }
  default:
    console.log(fs.readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').filter(l => l.startsWith('//')).map(l => l.slice(3)).join('\n'));
}
